"""Native storage for the RAM variables the GBA linker script places at fixed addresses.

Symbols at the same address share one block (they overlay each other on GBA).
A block is as large as the biggest native type declared for it, and at least as
large as its GBA region (up to the next fixed symbol), since decomp code often
indexes past a variable's declared type into the rest of its region. Symbols with
no C declaration get twice their region, enough if it holds only pointers.

Symbols that alias a field of a struct variable on GBA (hints.txt `=name
container.field`) are defined at that field's native offset instead.
"""

import re
from pathlib import Path

from .ctypes_db import TypeDB

ASSIGN_RE = re.compile(r"\.\s*=\s*(0x[0-9A-Fa-f]+)\s*;\s*(\w+)\s*=\s*\.\s*;")
REGION_RE = re.compile(r"^\s*(ewram|iwram)\s*\(NOLOAD\)", re.M)
REGION_BASE = {"ewram": 0x02000000, "iwram": 0x03000000}
REGION_SIZE = {"ewram": 0x40000, "iwram": 0x8000}


def fixed_symbols(linker_script: Path) -> list:
    """(address, name) for every RAM variable the preprocessed linker script defines."""
    text = linker_script.read_text()
    starts = [(m.start(), m.group(1)) for m in REGION_RE.finditer(text)]
    result = []
    for i, (start, region) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else text.find("rom", start)
        for m in ASSIGN_RE.finditer(text, start, end):
            name = m.group(2)
            if not name.startswith("ram_"):  # ARM code copied to IWRAM, not storage
                result.append((REGION_BASE[region] + int(m.group(1), 16), name))
    return sorted(result)


def emit_ram(linker_script: Path, linked: dict, types: TypeDB, aliases: dict, out: Path) -> Path:
    symbols = [(addr, name) for addr, name in fixed_symbols(linker_script) if name not in aliases]
    # Every RAM symbol in the linked ELF bounds the regions, including C-defined ones.
    bounds = sorted({addr for addr in linked.values() if (addr >> 24) in (0x02, 0x03)})
    groups = {}
    for addr, name in symbols:
        groups.setdefault(addr, []).append(name)

    lines = ["// Generated by port/tools/datagen from linker.ld; do not edit.", "", "\t.section __DATA,__bss"]
    for addr, names in sorted(groups.items()):
        region_end = (addr & 0xFF000000) + REGION_SIZE["ewram" if addr >> 24 == 2 else "iwram"]
        following = [b for b in bounds if addr < b < region_end]
        size = (following[0] if following else region_end) - addr
        declared = [types.decls.get(name) for name in names]
        if all(t is None for t in declared):
            size *= 2  # no C type: allow for every word being a widened pointer
        for t in declared:
            if t is not None and not (t[0] == "array" and t[2] is None) and t[0] not in ("func", "void"):
                size = max(size, types.layout(t, "native").size)
        lines.append("\t.p2align 4")
        for name in names:
            lines += [f"\t.globl _{name}", f"_{name}:"]
        lines.append(f"\t.space {size}")
    for name, (container, offset) in sorted(aliases.items()):
        lines += [f"\t.globl _{name}", f"_{name} = _{container} + {offset}"]
    out.write_text("\n".join(lines) + "\n")
    return out


def emit_ram_map(linked: dict, globals_: set, out: Path) -> Path:
    """gHwRamMap: (GBA address, size, native symbol) for every global RAM symbol.

    Used by HwGbaPtr to turn fixed EWRAM/IWRAM addresses in C code into native
    pointers. References are weak, so GBA-only symbols map to NULL.
    """
    entries = sorted(
        (addr, name) for name, addr in linked.items()
        if name in globals_ and (addr >> 24) in (0x02, 0x03) and not name.startswith(("ram_", "$"))
    )
    lines = ["// Generated by port/tools/datagen from tmc.elf; do not edit.", "", "\t.section __DATA,__const", "\t.p2align 3"]
    lines += [f"\t.weak_reference _{name}" for _, name in entries]
    lines += ["\t.globl _gHwRamMap", "_gHwRamMap:"]
    for i, (addr, name) in enumerate(entries):
        region_end = (addr & 0xFF000000) + REGION_SIZE["ewram" if addr >> 24 == 2 else "iwram"]
        end = next((a for a, _ in entries[i + 1 :] if a > addr), region_end)
        lines += [f"\t.long {addr:#x}, {end - addr:#x}", f"\t.quad _{name}"]
    lines += ["\t.globl _gHwRamMapCount", "\t.p2align 2", "_gHwRamMapCount:", f"\t.long {len(entries)}"]
    out.write_text("\n".join(lines) + "\n")
    return out
