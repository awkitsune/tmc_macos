"""gSoundRomMap: GBA ROM address -> native pointer for the sound data.

Song bytecode keeps absolute GBA addresses (GOTO/PATT targets, the voicegroup and
track pointers in song headers, XCMD wave pointers) with no relocations, so the
native m4a engine translates them at runtime (port/src/sound/m4a_addr.c).

Each entry covers one stretch of a section: a run of byte-for-byte labels is one
linear entry (native = start + offset), a re-laid-out table (the voicegroups'
ToneData) is an entry with its GBA and native element strides. Entries are
sorted and do not overlap. Anchors are global labels, so the table can live in
its own file.
"""

from pathlib import Path

SOUND_OBJECTS = "data/sound/"
LINEAR = ("raw", "script", "split", "code")


def _segments(model, obj, sec):
    """(gba start, gba end, gba stride, native stride, anchor expression) for a section."""
    segs = []
    for label in sec.labels:
        info = model.labels[(obj.rel, label.name)]
        if info.mode in LINEAR:
            if segs and segs[-1]["linear"]:
                segs[-1]["end"] = label.end
            else:
                start = 0 if not segs else label.offset
                segs.append({"linear": True, "start": start, "end": label.end, "labels": []})
            segs[-1]["labels"].append(label)
        else:
            if info.mode == "ptrs":
                gstride, nstride = 4, 8
            else:
                gstride = model.types.layout(info.type, "gba").size
                nstride = model.types.layout(info.type, "native").size
            segs.append({"linear": False, "start": label.offset, "end": label.end, "labels": [label],
                         "gstride": gstride, "nstride": nstride})
    out = []
    for seg in segs:
        anchor = next((l for l in seg["labels"] if l.is_global), None)
        if anchor is None:
            raise ValueError(f"{obj.rel}{sec.name}+{seg['start']:#x}: no global label to anchor the sound map")
        if seg["linear"]:
            delta = anchor.offset - seg["start"]
            expr = f"_{anchor.name}" + (f" - {delta}" if delta else "")
            out.append((sec.base + seg["start"], sec.base + seg["end"], 0, 0, expr))
        else:
            out.append((sec.base + seg["start"], sec.base + seg["end"], seg["gstride"], seg["nstride"], f"_{anchor.name}"))
    return out


def emit_sound_map(model, objects: list, out: Path) -> Path:
    entries = []
    for obj in objects:
        if not obj.rel.startswith(SOUND_OBJECTS):
            continue
        for sec in obj.sections:
            entries += _segments(model, obj, sec)
    entries.sort()
    lines = ["// Generated by port/tools/datagen from data/sound; do not edit.", "", "\t.section __DATA,__const", "\t.p2align 3"]
    lines += ["\t.globl _gSoundRomMap", "_gSoundRomMap:"]
    for start, end, gstride, nstride, expr in entries:
        lines += [f"\t.long {start:#x}, {end - start:#x}", f"\t.short {gstride}, {nstride}", "\t.space 4", f"\t.quad {expr}"]
    lines += ["\t.globl _gSoundRomMapCount", "\t.p2align 2", "_gSoundRomMapCount:", f"\t.long {len(entries)}"]
    out.write_text("\n".join(lines) + "\n")
    return out
