"""Generate the area renderer's table of loadable rooms (port/src/arearender.c).

usage: area_rooms.py out.c

The rooms are the room smoke test's (room_smoke_rooms.py): a header with a tile
set, room properties, a map entry and a tile set entry. The lengths of the map
and tile set lists are only in data/map/*.s, so the renderer could not tell a
past the end entry from a real one at run time.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import room_smoke_rooms  # noqa: E402


def main():
    areas = len(room_smoke_rooms.words(room_smoke_rooms.SYMS["gAreaRoomHeaders"]))
    masks = [0] * areas
    for spec in room_smoke_rooms.rooms()[0]:
        area, room = (int(x, 16) for x in spec.split(":"))
        masks[area] |= 1 << room
    lines = [
        "// Generated by port/scripts/area_rooms.py from data/map/*.s; do not edit.",
        "#include <stdint.h>",
        "",
        f"const int gAreaMapAreaCount = {areas};",
        "// Bit r of entry a: room r of area a can be loaded.",
        f"const uint64_t gAreaMapLoadableRooms[{areas}] = {{",
    ]
    lines += [f"    0x{m:016x}," for m in masks]
    lines += ["};", ""]
    open(sys.argv[1], "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
