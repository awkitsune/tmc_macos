"""Generate the song exporter's name table from the game sources.

usage: song_names.py include/sound.h src/sound.c out.c

Song numbers come from the Sound enum in include/sound.h (sequential up to the
first explicit value); gSongTable's initialisers in src/sound.c give each one's
data label. Titles are the enum names without their BGM_/SFX_ prefix, in title
case.
"""

import re
import sys


def enum_values(header: str) -> dict:
    body = re.search(r"typedef enum \{(.*?)\} Sound;", header, re.S).group(1)
    values, n = {}, 0
    for line in body.splitlines():
        line = line.split("//")[0].strip().rstrip(",")
        if not line:
            continue
        if "=" in line:
            break  # the special SONG_* commands
        values[line] = n
        n += 1
    return values


def title(enum: str) -> str:
    words = enum.split("_")
    if words[0] in ("BGM", "SFX"):
        words = words[1:]
    if not words:
        return enum
    return " ".join(w if any(c.isdigit() for c in w) else w.capitalize() for w in words)


def main():
    header, source, out = sys.argv[1:4]
    values = enum_values(open(header).read())
    table = re.search(r"const Song gSongTable\[\] = \{(.*?)\n\};", open(source).read(), re.S).group(1)
    entries = {}
    for m in re.finditer(r"\[(\w+)\]\s*=\s*\{\s*&(\w+)", table):
        entries[values[m.group(1)]] = (m.group(1), m.group(2))
    count = max(entries) + 1
    lines = [
        "// Generated by port/scripts/song_names.py from include/sound.h and src/sound.c; do not edit.",
        '#include "song_names.h"',
        "",
        f"const int gSongNameCount = {count};",
        "const SongName gSongNames[] = {",
    ]
    for i in range(count):
        enum, label = entries.get(i, ("", ""))
        lines.append(f'    {{ "{enum}", "{label}", "{title(enum) if enum else ""}" }},')
    lines += ["};", ""]
    open(out, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
