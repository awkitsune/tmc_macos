"""Generate the app's room name table from the game sources.

usage: room_names.py include/area.h include/roomid.h out.c

Area numbers come from the area enum in include/area.h (sequential from
AREA_MINISH_WOODS); include/roomid.h lists each area's rooms under an
"// AREA_*" comment, numbered from 0. Names are the enum names in title case:
an area's is its own, a room's is "Area – Room" with the area's words taken off
the front of the room's. Placeholder names (AREA_NULL_*, AREA_37, ROOM_*_MAIN,
ROOM_*_1a) have none: a room without one shows its area's name, an area without
one nothing.
"""

import re
import sys

# Words that title case gets wrong.
WORDS = {
    "MT": "Mt.",
    "OF": "of",
    "TO": "to",
    "AND": "and",
    "VAATIS": "Vaati's",
    "SIMONS": "Simon's",
    "LINKS": "Link's",
    "MELARIS": "Melari's",
    "PERCYS": "Percy's",
    "MAYORS": "Mayor's",
    "TOMPAS": "Tompa's",
    "BOSSKEY": "Boss Key",
    "FOUINTAIN": "Fountain",
    "PATH1": "Path 1",
    "PATH2": "Path 2",
}
# Words left out of a name ("GENTARI_MAIN" is Gentari's room).
DROP = {"MAIN"}


def placeholder(words) -> bool:
    """A name that is only a number or hex index (AREA_37, ROOM_X_1a, NULL_8E)."""
    if not words or words[0] in ("EMPTY", "NOT") or re.fullmatch(r"NULL\d*", words[0]):
        return True
    return all(re.fullmatch(r"[0-9A-Fa-f]{1,2}", w) for w in words)


def title(words) -> str:
    out = []
    for i, w in enumerate(w for w in words if w.upper() not in DROP):
        up = w.upper()
        if up in WORDS:
            text = WORDS[up]
            out.append(text[0].upper() + text[1:] if i == 0 else text)
        elif any(c.isdigit() for c in w):
            out.append(up)
        else:
            out.append(w.capitalize())
    return " ".join(out)


def c_string(text) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"' if text else "NULL"


def main():
    area_h, roomid_h, out = sys.argv[1:4]
    body = re.search(r"typedef enum \{\s*(AREA_MINISH_WOODS.*?)\}", open(area_h).read(), re.S).group(1)
    areas = [line.split("//")[0].strip().rstrip(",") for line in body.splitlines()]
    areas = [a for a in areas if a]
    assert all("=" not in a for a in areas)

    rooms = {}
    current = None
    for line in open(roomid_h).read().splitlines():
        line = line.strip()
        m = re.fullmatch(r"//\s*(AREA_\w+)", line)
        if m:
            current = m.group(1)
            rooms[current] = []
            continue
        m = re.match(r"(ROOM_\w+)", line)
        if m and current is not None:
            rooms[current].append(m.group(1))

    area_names = []
    for area in areas:
        words = area[len("AREA_"):].split("_")
        area_names.append(None if placeholder(words) else title(words))

    lines = [
        "// Generated by port/scripts/room_names.py from include/area.h and include/roomid.h; do not edit.",
        '#include "roomname.h"',
        "",
        "#include <stddef.h>",
        "",
    ]
    for index, area in enumerate(areas):
        prefix = area[len("AREA_"):].split("_")
        names = []
        for room in rooms.get(area, []):
            words = room[len("ROOM_"):].split("_")
            if words[: len(prefix)] == prefix:
                words = words[len(prefix):]
            words = [w for w in words if w.upper() not in DROP]
            if placeholder(words) or area_names[index] is None:
                names.append(None)
            else:
                names.append(f"{area_names[index]} – {title(words)}")
        lines.append(f"static const char* const sRooms{index:02X}[] = {{")
        lines += [f"    {c_string(n)}," for n in names] or ["    NULL,"]
        lines.append("};")
    lines += [
        "",
        "static const struct {",
        "    const char* name;",
        "    const char* const* rooms;",
        "    int roomCount;",
        "} sAreas[] = {",
    ]
    for index, area in enumerate(areas):
        count = len(rooms.get(area, []))
        lines.append(f"    {{ {c_string(area_names[index])}, sRooms{index:02X}, {count} }}, // {area}")
    lines += [
        "};",
        "",
        "const char* RoomName(int area, int room) {",
        "    if (area < 0 || area >= (int)(sizeof(sAreas) / sizeof(sAreas[0]))) {",
        "        return NULL;",
        "    }",
        "    if (room >= 0 && room < sAreas[area].roomCount && sAreas[area].rooms[room] != NULL) {",
        "        return sAreas[area].rooms[room];",
        "    }",
        "    return sAreas[area].name;",
        "}",
        "",
    ]
    open(out, "w", encoding="utf-8").write("\n".join(lines))


if __name__ == "__main__":
    main()
